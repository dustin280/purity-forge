// Regenerates src/lib/lims/coc/photon-wasm-base64.generated.ts from the
// currently-installed @cf-wasm/photon package. Run after any version bump
// of that dependency: `node scripts/gen-photon-wasm-b64.mjs`.
//
// Why this exists: Rollup (this app's SSR/dev-server build) does not
// support the raw ESM `.wasm` import @cf-wasm/photon/dist/workerd.js uses
// internally ("ESM integration proposal for Wasm is not supported
// currently" — confirmed against a real production build failure). The
// /others entrypoint takes wasm bytes directly via initPhoton() instead of
// importing a .wasm file, so embedding the bytes as a base64 string
// sidesteps the unsupported import entirely — no .wasm import appears
// anywhere in the bundled dependency graph.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const wasmPath = join(
  __dirname,
  "..",
  "node_modules",
  "@cf-wasm",
  "photon",
  "dist",
  "lib",
  "photon_rs_bg.wasm",
);
const outPath = join(
  __dirname,
  "..",
  "src",
  "lib",
  "lims",
  "coc",
  "photon-wasm-base64.generated.ts",
);

const bytes = readFileSync(wasmPath);
const b64 = bytes.toString("base64");

const out =
  `// Auto-generated by scripts/gen-photon-wasm-b64.mjs from\n` +
  `// node_modules/@cf-wasm/photon/dist/lib/photon_rs_bg.wasm.\n` +
  `// Embedded as a base64 string (not a bundler-level .wasm import) because Rollup —\n` +
  `// used for this app's SSR/dev-server build — does not support the raw ESM .wasm\n` +
  `// import @cf-wasm/photon/workerd.js uses internally (confirmed live: "ESM\n` +
  `// integration proposal for Wasm is not supported currently"). Passing bytes\n` +
  `// directly to initPhoton() via the /others entrypoint sidesteps that entirely —\n` +
  `// no .wasm import appears anywhere in the bundled dependency graph.\n` +
  `// To regenerate after a @cf-wasm/photon version bump: node scripts/gen-photon-wasm-b64.mjs\n` +
  `export const PHOTON_WASM_BASE64 = "${b64}";\n`;

writeFileSync(outPath, out);
console.log(`Wrote ${outPath} (${out.length} bytes, source wasm ${bytes.length} bytes)`);
